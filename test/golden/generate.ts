// Builds the golden vectors by running the real projection engine over the
// inputs in cases.ts. Shared by the generator script and by the test that fails
// when the committed file has gone stale.
//
// Keep this file free of non-erasable TypeScript: the script runs it through
// Node's type stripping.

import { computeCorrectionAccuracy, computeSinkingFundContribution, mergeCheckpoints, projectBalance, sumProjections } from '../../electron/main/projection.ts';
import { correctionAccuracyCases, mergeCheckpointsCases, projectBalanceCases, sinkingFundCases, sumProjectionsCases } from './cases.ts';

/** Bump when the shape of the file changes, so a consumer can refuse a layout it doesn't know. */
export const GOLDEN_FORMAT_VERSION = 1;

export function buildGoldenVectors() {
  return {
    formatVersion: GOLDEN_FORMAT_VERSION,
    source: 'electron/main/projection.ts',
    notes: [
      'Generated by `npm run golden` in simple-budget. Do not edit by hand.',
      'Amounts are signed integer cents; dates are ISO YYYY-MM-DD with no time zone.',
      'Each case lists its inputs and the exact output the desktop engine produced.',
    ],
    projectBalance: projectBalanceCases.map(({ name, ...input }) => ({ name, input, expected: projectBalance(input) })),
    mergeCheckpoints: mergeCheckpointsCases.map(({ name, ...input }) => ({ name, input, expected: mergeCheckpoints(input.starting, input.additional) })),
    sumProjections: sumProjectionsCases.map(({ name, series }) => ({ name, input: { series }, expected: sumProjections(series.map((s) => projectBalance(s))) })),
    sinkingFundContribution: sinkingFundCases.map(({ name, ...input }) => ({ name, input, expected: computeSinkingFundContribution(input.item, input.today) })),
    correctionAccuracy: correctionAccuracyCases.map(({ name, ...input }) => ({ name, input, expected: computeCorrectionAccuracy(input.checkpoints, input.items) })),
  };
}

const LINE_WIDTH = 240;

/**
 * Pretty-prints JSON but keeps anything that fits on one line on one line, so a
 * 400-day projection is 400 readable rows rather than 4,000, and the diff for a
 * changed day is a changed line. Output is deterministic.
 */
export function formatGolden(value: unknown, indent = ''): string {
  const compact = JSON.stringify(value);
  if (typeof value !== 'object' || value === null || compact.length + indent.length <= LINE_WIDTH) {
    return compact;
  }
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    return `[\n${value.map((entry) => `${inner}${formatGolden(entry, inner)}`).join(',\n')}\n${indent}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>);
  return `{\n${entries.map(([key, entry]) => `${inner}${JSON.stringify(key)}: ${formatGolden(entry, inner)}`).join(',\n')}\n${indent}}`;
}

export function renderGoldenVectors(): string {
  return `${formatGolden(buildGoldenVectors())}\n`;
}
